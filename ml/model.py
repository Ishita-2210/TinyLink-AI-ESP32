"""Safe JSON tree artifact, no pickle deserialization or sklearn runtime needed."""
import hashlib
import json
import math
from pathlib import Path

from host.schema import LABELS, NAMES, SCHEMA, SCHEMA_HASH, vector


def fingerprint(model):
    payload = {k: v for k, v in model.items() if k != "model_id"}
    return hashlib.sha256(json.dumps(payload, sort_keys=True, separators=(",", ":"), allow_nan=False).encode()).hexdigest()[:16]


def load_model(path):
    model = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(model, dict): raise ValueError("model must be an object")
    if model.get("schema_version") != SCHEMA["schema_version"] or model.get("schema_sha256") != SCHEMA_HASH or model.get("features") != NAMES or model.get("labels") != LABELS:
        raise ValueError("incompatible model schema")
    if fingerprint(model) != model.get("model_id"):
        raise ValueError("model fingerprint mismatch")
    nodes = model.get("nodes", [])
    if not isinstance(nodes, list) or not nodes or len(nodes) > 255 or any(not isinstance(n, dict) for n in nodes):
        raise ValueError("invalid tree size")
    visited = set()
    def visit(i):
        if isinstance(i, bool) or not isinstance(i, int) or not 0 <= i < len(nodes) or i in visited:
            raise ValueError("invalid tree topology")
        visited.add(i)
        node = nodes[i]
        if "prediction" in node:
            if type(node["prediction"]) is not int or node["prediction"] not in range(3):
                raise ValueError("invalid leaf")
        else:
            if type(node.get("feature")) is not int or node["feature"] not in range(len(NAMES)) or type(node.get("threshold")) not in (float, int) or not math.isfinite(node["threshold"]):
                raise ValueError("invalid split")
            visit(node.get("left")); visit(node.get("right"))
    visit(0)
    if len(visited) != len(nodes):
        raise ValueError("unreachable tree nodes")
    return model


def predict_vector(model, x):
    i = 0
    while "prediction" not in model["nodes"][i]:
        node = model["nodes"][i]
        i = node["left"] if float(x[node["feature"]]) <= node["threshold"] else node["right"]
    return model["nodes"][i]["prediction"]


def predict(model, features):
    return predict_vector(model, vector(features))


def export_header(model):
    def branch(i, indent):
        node = model["nodes"][i]
        if "prediction" in node:
            return f"{indent}return {node['prediction']};\n"
        text = f"{indent}if (static_cast<double>(x[{node['feature']}]) <= {node['threshold']!r}) {{\n"
        return text + branch(node["left"], indent + "  ") + f"{indent}}} else {{\n" + branch(node["right"], indent + "  ") + f"{indent}}}\n"
    return ("// Generated by python -m ml.train; float32 inputs, exact float64 thresholds.\n"
            "#pragma once\n#include \"schema_generated.h\"\nnamespace tinylink {\n"
            "constexpr bool modelSchemaMatches() {\n"
            f"  const char* expected = \"{model['schema_sha256']}\";\n"
            "  for (unsigned i = 0; i < 65; ++i) if (expected[i] != kSchemaHash[i]) return false;\n"
            "  return true;\n}\n"
            "static_assert(modelSchemaMatches(), \"Model/schema drift: regenerate schema and retrain\");\n"
            f"constexpr const char* kModelId = \"{model['model_id']}\";\n"
            f"constexpr unsigned kModelNodes = {len(model['nodes'])};\n"
            "inline int modelPredict(const float* x) {\n" + branch(0, "  ") + "}\n}\n")
