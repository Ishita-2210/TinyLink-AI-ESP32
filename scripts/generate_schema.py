"""Generate the firmware contract. --check rejects schema/header drift."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render():
    raw = (ROOT / "schema/features.json").read_bytes()
    s = json.loads(raw)
    def arr(key):
        return ", ".join(str(f[key] if f[key] is not None else 0) for f in s["features"])
    names = ", ".join(json.dumps(f["name"]) for f in s["features"])
    labels = ", ".join(json.dumps(x) for x in s["labels"])
    nullable = ", ".join("true" if f["missing"] is not None else "false" for f in s["features"])
    return f'''// Generated by scripts/generate_schema.py; edit schema/features.json.
#pragma once
#include <cstddef>
#include <cstdint>
namespace tinylink {{
constexpr unsigned kSchemaVersion = {s['schema_version']};
constexpr unsigned kProtocolVersion = {s['protocol_version']};
constexpr size_t kFeatureCount = {len(s['features'])};
constexpr size_t kWindow = {s['window_samples']};
constexpr uint32_t kSampleMs = {s['sample_interval_ms']};
constexpr uint32_t kTimeoutMs = {s['probe_timeout_ms']};
constexpr uint32_t kMaxSampleAgeMs = {s['max_sample_age_ms']};
constexpr const char* kSchemaHash = "{hashlib.sha256(raw).hexdigest()}";
constexpr const char* kFeatureNames[] = {{{names}}};
constexpr const char* kLabels[] = {{{labels}}};
constexpr float kMin[] = {{{arr('min')}}};
constexpr float kMax[] = {{{arr('max')}}};
constexpr float kMissing[] = {{{arr('missing')}}};
constexpr bool kNullable[] = {{{nullable}}};
}}  // namespace tinylink
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "firmware/include/schema_generated.h"
    content = render()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("generated schema is stale; run python scripts/generate_schema.py")
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
